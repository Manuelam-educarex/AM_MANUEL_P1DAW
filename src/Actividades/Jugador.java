package Actividades;

public class Jugador {
	
	private String posicion;
	private int dorsal;
	
	
	public Jugador(String posicion, int dorsal) {
		super();
		this.posicion = posicion;
		this.dorsal = dorsal;
	}


	public String getPosicion() {
		return posicion;
	}


	public int getDorsal() {
		return dorsal;
	}
	
	
	

}
